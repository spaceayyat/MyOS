#!/usr/bin/env bash
# Resolve the current digest of the Fedora bootc base tag and record it in
# image/base-image.env so builds are reproducible. This only READS from the
# registry and writes one local file. Review the diff before committing it.
#
# Usage: scripts/pin-base-digest.sh [tag-reference]
#   default reference: quay.io/fedora/fedora-bootc:44
set -euo pipefail
# shellcheck source=scripts/lib.sh
. "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

ref="${1:-${DEFAULT_BASE}}"
[[ "${ref}" == *@sha256:* ]] && die "Give a tag reference (e.g. ${DEFAULT_BASE}), not a digest."

require_cmd skopeo "Install it: sudo apt install -y skopeo"

info "Resolving digest for ${ref} ..."
digest="$(skopeo inspect --format '{{.Digest}}' "docker://${ref}" 2>/dev/null)" \
  || die "Could not inspect ${ref}. Check your network and that the tag exists."
[[ "${digest}" =~ ^sha256:[0-9a-f]{64}$ ]] || die "Unexpected digest value: '${digest}'"

repo="${ref%:*}"
pinned="${repo}:${ref##*:}@${digest}"

if [[ -f "${BASE_ENV_FILE}" ]]; then
  info "Existing ${BASE_ENV_FILE} will be replaced (git diff shows the change)."
fi

cat > "${BASE_ENV_FILE}" <<EOF
# Generated by scripts/pin-base-digest.sh - do not edit by hand.
# Tag was ${ref} when pinned. Re-run the script to update, then review the diff.
BASE_IMAGE_PINNED="${pinned}"
EOF
info "Pinned: ${pinned}"
