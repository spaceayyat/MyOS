#!/usr/bin/env python3
"""Build the VYLO logo files by tracing the original artwork.

Sources (assets/brand/source/):
    vylo-mark-indigo.png   the mark
    vylo-logo-2.jpg        the mark with the VYLO lettering
Needs numpy, Pillow, contourpy and rsvg-convert.
    python3 scripts/make-logo.py
"""
import pathlib
import subprocess

import contourpy
import numpy as np
from PIL import Image, ImageDraw

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "assets" / "brand"
SRC = OUT / "source"
INDIGO, LILAC, VOID, WHITE = "#4A47FF", "#C278FF", "#100B25", "#F4F2FF"


def simplify(points, tolerance):
    """Douglas-Peucker."""
    keep = np.zeros(len(points), bool)
    keep[[0, -1]] = True
    stack = [(0, len(points) - 1)]
    while stack:
        a, b = stack.pop()
        if b <= a + 1:
            continue
        start, end, middle = points[a], points[b], points[a + 1:b]
        line = end - start
        length = np.hypot(*line)
        if length == 0:
            dist = np.hypot(*(middle - start).T)
        else:
            dist = np.abs(line[0] * (middle[:, 1] - start[1]) - line[1] * (middle[:, 0] - start[0])) / length
        i = int(dist.argmax())
        if dist[i] > tolerance:
            keep[a + 1 + i] = True
            stack += [(a, a + 1 + i), (a + 1 + i, b)]
    return points[keep]


def trace(path, box=None):
    """SVG path data and bounding box of the coloured shapes on white."""
    image = Image.open(path).convert("RGB")
    if box:
        image = image.crop(box)
    red = np.asarray(image, np.float32)[..., 0]
    ink = red[red < 235]
    solid = np.percentile(ink, 20)                  # red value of full colour
    cover = np.pad(np.clip((255 - red) / (255 - solid), 0, 1), 1)
    parts, everything = [], []
    for line in contourpy.contour_generator(z=cover).lines(0.5):
        if len(line) < 20:                          # compression specks
            continue
        line = simplify(line, 0.7)
        everything.append(line)
        parts.append("M" + " L".join(f"{x:.1f} {y:.1f}" for x, y in line[:-1]) + " Z")
    points = np.concatenate(everything)
    x0, y0 = points.min(0)
    x1, y1 = points.max(0)
    return "".join(parts), (x0, y0, x1 - x0, y1 - y0)


def svg(box, body, width=None, pad=0.0):
    x, y, w, h = box
    p = max(w, h) * pad
    x, y, w, h = x - p, y - p, w + 2 * p, h + 2 * p
    width = width or round(w / 4)
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{round(width * h / w)}" '
            f'viewBox="{x:.0f} {y:.0f} {w:.0f} {h:.0f}" role="img" aria-label="VYLO">{body}</svg>\n')


def shape(d, colour):
    return f'<path fill="{colour}" fill-rule="evenodd" d="{d}"/>'


def qml(mark, mark_box, word, word_box):
    """A QML component that paints the logo in any colour."""
    def box(b):
        return " ".join(f"{v:.0f}" for v in b)
    return f'''import QtQuick

// Generated by scripts/make-logo.py. The logo in whatever colour the theme asks
// for: Logo {{ colour: th.accent; height: 24 }}   or   Logo {{ word: true; ... }}
Image {{
    id: logo
    property color colour: "{INDIGO}"
    property bool word: false

    readonly property string markPath: "{mark}"
    readonly property string wordPath: "{word}"

    fillMode: Image.PreserveAspectFit
    width: height * (word ? {word_box[2] / word_box[3]:.4f} : {mark_box[2] / mark_box[3]:.4f})
    sourceSize.height: height * 2
    source: "data:image/svg+xml;utf8," + encodeURIComponent(
        "<svg xmlns='http://www.w3.org/2000/svg' width='" + (word ? {word_box[2] / 4:.0f} : {mark_box[2] / 4:.0f})
        + "' height='" + (word ? {word_box[3] / 4:.0f} : {mark_box[3] / 4:.0f})
        + "' viewBox='" + (word ? "{box(word_box)}" : "{box(mark_box)}")
        + "'><path fill-rule='evenodd' fill='" + String(logo.colour).replace(/^#ff(?=.{{6}}$)/i, "#")
        + "' d='" + (word ? logo.wordPath : logo.markPath) + "'/></svg>")
}}
'''


def render(source, target, width):
    subprocess.run(["rsvg-convert", "-w", str(width), "-o", str(target), str(source)], check=True)


def main():
    mark, mark_box = trace(SRC / "vylo-mark-indigo.png")
    word, word_box = trace(SRC / "vylo-logo-2.jpg", (0, 640, 1932, 1080))
    top, top_box = trace(SRC / "vylo-logo-2.jpg", (0, 0, 1932, 640))
    # The lettering was traced from a crop that starts 640 px down.
    wx, wy, ww, wh = word_box
    stack_box = (wx, top_box[1], ww, wy + 640 + wh - top_box[1])

    files = {
        "vylo-mark.svg": svg(mark_box, shape(mark, INDIGO)),
        "vylo-mark-lilac.svg": svg(mark_box, shape(mark, LILAC)),
        "vylo-mark-mono.svg": svg(mark_box, shape(mark, "#000000")),
        "vylo-wordmark.svg": svg(word_box, shape(word, INDIGO)),
    }
    for name, letters in (("vylo-logo.svg", INDIGO), ("vylo-logo-dark.svg", WHITE)):
        body = shape(top, INDIGO) + f'<g transform="translate(0 640)">{shape(word, letters)}</g>'
        files[name] = svg(stack_box, body)
    mx, my, mw, mh = mark_box
    side = max(mw, mh) * 1.5
    cx, cy = mx + mw / 2, my + mh / 2
    tile = (cx - side / 2, cy - side / 2, side, side)
    files["vylo-app-icon.svg"] = svg(tile, f'<rect x="{tile[0]:.0f}" y="{tile[1]:.0f}" width="{side:.0f}" height="{side:.0f}" '
                                           f'rx="{side * 0.23:.0f}" fill="{INDIGO}"/>' + shape(mark, "#ffffff"), width=256)
    for name, text in files.items():
        (OUT / name).write_text(text)
    (ROOT / "shared/ui/Logo.qml").write_text(qml(mark, mark_box, word, word_box))

    # Pictures for the boot splash and the login screen.
    config = ROOT / "image/config/rootfs-vylo/usr/share"
    for folder, width in (("sddm/themes/vylo", 360), ("plymouth/themes/vylo", 300)):
        render(OUT / "vylo-logo-dark.svg", config / folder / "logo.png", width)
    dot = Image.new("RGBA", (40, 40), (0, 0, 0, 0))
    ImageDraw.Draw(dot).ellipse((0, 0, 39, 39), fill=(74, 71, 255, 255))
    dot.resize((10, 10), Image.LANCZOS).save(config / "plymouth/themes/vylo/dot.png")
    print("wrote the logo set to", OUT)


if __name__ == "__main__":
    main()
